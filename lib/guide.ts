/** A message a developer can act on without opening the panel: what's wrong, on which pages, what to do. */
export function devBrief(project: ProjectRow): string {
  const pid = project.id;
  const groups = new Map<string, string[]>();
  for (const r of q<{ code: string; url: string; severity: string }>(
    "SELECT code, url, severity FROM issues WHERE project_id=? AND status='open' AND severity IN ('critical','warning') ORDER BY severity, code", pid,
  )) {
    if (!groups.has(r.code)) groups.set(r.code, []);
    groups.get(r.code)!.push(r.url);
  }
  if (!groups.size) return "";
  const out = [`مشکلات فنی ${project.domain} که باید در کد سایت رفع شوند:`];
  for (const [code, urls] of groups) {
    const g = GUIDE[code];
    const label = CHECKS[code]?.[1] ?? code;
    out.push(`\n${label} (${urls.length} صفحه)`);
    if (g?.cause) out.push(`علت: ${g.cause}`);
    out.push(...(g?.steps || []).slice(0, 4).map((s) => `- ${s}`));
    out.push(...urls.slice(0, 5).map((u) => `  ${u}`));
    if (urls.length > 5) out.push(`  و ${urls.length - 5} صفحه دیگر`);
  }
  return out.join("\n");
}
